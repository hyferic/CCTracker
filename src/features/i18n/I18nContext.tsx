export type MessageKey = keyof (typeof messages)['en'];

const recurrenceTypeKeys: Record<RecurrenceType, MessageKey> = {
  one_time: 'recurrence.oneTime',
  monthly: 'recurrence.monthly',
  quarterly: 'recurrence.quarterly',
  semiannual: 'recurrence.semiannual',
  annual: 'recurrence.annual',
  custom: 'recurrence.custom',
};

const recurrenceBasisKeys: Record<Exclude<RecurrenceBasis, 'none'>, MessageKey> = {
  calendar: 'recurrence.calendar',
  anniversary: 'recurrence.anniversary',
};

export function recurrenceLabel(
  type: RecurrenceType,
  basis: RecurrenceBasis,
  t: (key: MessageKey) => string,
) {
  const typeLabel = t(recurrenceTypeKeys[type]);
  if (type === 'one_time') return typeLabel;
  return `${typeLabel} · ${t(recurrenceBasisKeys[basis === 'anniversary' ? 'anniversary' : 'calendar'])}`;
}

export function recurrenceTypeLabel(type: RecurrenceType, t: (key: MessageKey) => string) {
  return t(recurrenceTypeKeys[type]);
}

interface I18nValue {
  language: Language;
  setLanguage: (language: Language) => Promise<void>;
  t: (key: MessageKey) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function initialLanguage(profileLanguage?: Profile['language']): Language {
  if (profileLanguage) return profileLanguage;
  if (typeof window !== 'undefined') {
    const saved = readStoredLanguage();
    if (saved === 'en' || saved === 'zh-CN') return saved;
    if (navigator.language.toLowerCase().startsWith('zh')) return 'zh-CN';
  }
  return 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const profileContext = useContext(ProfileContext);
  const [language, setLanguageState] = useState<Language>(() =>
    initialLanguage(profileContext?.profile.language),
  );
  const setLanguage = useCallback(
    async (next: Language) => {
      const previous = language;
      setLanguageState(next);
      storeLanguage(next);
      try {
        const profile = await updateProfileLanguage(next);
        profileContext?.replaceProfile(profile);
      } catch (caught) {
        setLanguageState(previous);
        storeLanguage(previous);
        throw caught;
      }
    },
    [language, profileContext],
  );
  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);
  const value = useMemo<I18nValue>(
    () => ({
      language,
      setLanguage,
      t: (key) => messages[language][key] ?? messages.en[key],
    }),
    [language, setLanguage],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used inside I18nProvider.');
  return value;
}

export function useOptionalI18n() {
  return useContext(I18nContext);
}
